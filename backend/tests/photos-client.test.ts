import {beforeEach,expect,test,vi} from 'vitest';
const {manipulate,read,permission,info,pick,size,library,copy,uuid}=vi.hoisted(()=>({manipulate:vi.fn(),read:vi.fn(),permission:vi.fn(),info:vi.fn(),pick:vi.fn(),size:vi.fn(),library:vi.fn(),copy:vi.fn(),uuid:vi.fn()}));
vi.mock('../../frontend/node_modules/expo-crypto',()=>({randomUUID:uuid}));
vi.mock('../../frontend/node_modules/expo-file-system/legacy',()=>({copyAsync:copy}));
vi.mock('../../frontend/node_modules/react-native',()=>({Platform:{OS:'android'},Image:{getSize:size}}));
vi.mock('../../frontend/node_modules/expo-image-picker',()=>({launchImageLibraryAsync:library}));
vi.mock('../../frontend/node_modules/expo-document-picker',()=>({getDocumentAsync:pick}));
vi.mock('../../frontend/node_modules/expo-media-library',()=>({requestPermissionsAsync:permission,getAssetInfoAsync:info}));
vi.mock('../../frontend/node_modules/expo-image-manipulator',()=>({manipulateAsync:manipulate,SaveFormat:{JPEG:'jpeg'}}));
vi.mock('../../frontend/node_modules/expo-file-system',()=>({
 Paths:{cache:{uri:'file:///app/cache/'}},
 File:class {
  uri:string;
  constructor(first:string|{uri:string},...parts:string[]){this.uri=typeof first==='string'?first:first.uri;for(const part of parts)this.uri=this.uri.replace(/\/$/,'')+'/'+part;}
  exists=true;size=100;arrayBuffer=read;
 },
}));
import {compressPhoto,photoMetadata,photoPermission,pickPhotos} from '../../frontend/src/photos';
const asset={uri:'file:///selected.jpg',width:4000,height:3000,assetId:'123'};
beforeEach(()=>{vi.resetAllMocks();uuid.mockReturnValue('selected-photo');});
test('explicit Android original selection caches bytes and keeps media ID; limited access uses system picker',async()=>{
 pick.mockResolvedValue({canceled:false,assets:[{uri:'content://com.android.providers.media.documents/document/image%3A36',name:'selected.jpg',size:100,mimeType:'image/jpeg'}]});size.mockResolvedValue({width:2400,height:1600});
 info.mockResolvedValue({width:2400,height:1600});
 expect((await pickPhotos(true,'original')).assets?.[0]).toMatchObject({uri:'file:///app/cache/selected-photo.jpg',assetId:'36',width:2400,height:1600,fileSize:100});
 expect(pick).toHaveBeenCalledWith({type:['image/jpeg','image/png'],multiple:true,copyToCacheDirectory:false});
 expect(copy).toHaveBeenCalledWith({from:'content://com.android.providers.media.documents/document/image%3A36',to:'file:///app/cache/selected-photo.jpg'});
 expect(size).toHaveBeenCalledWith('file:///app/cache/selected-photo.jpg');
 library.mockResolvedValue({canceled:true,assets:null});expect((await pickPhotos(false,'original')).canceled).toBe(true);
 expect(library).toHaveBeenCalledWith({mediaTypes:['images'],allowsMultipleSelection:true,selectionLimit:20,exif:true});
 pick.mockResolvedValue({canceled:true});expect((await pickPhotos(true,'original')).canceled).toBe(true);
});
test('compression enforces actual output dimensions when Android reports a smaller source',async()=>{
 manipulate.mockResolvedValueOnce({uri:'file:///large.jpg',width:2400,height:1600}).mockResolvedValueOnce({uri:'file:///small.jpg',width:2048,height:1365});read.mockResolvedValue(new ArrayBuffer(90));
 const result=await compressPhoto({...asset,width:1200,height:800},2048,100);
 expect(result.width).toBe(2048);expect(manipulate).toHaveBeenLastCalledWith(asset.uri,[{resize:{width:2048}}],{compress:.8,format:'jpeg'});
});
test('Android redacted GPS zero values are missing metadata rather than a real location',async()=>{
 expect(await photoMetadata({...asset,assetId:null,exif:{GPSLatitude:0,GPSLatitudeRef:'',GPSLongitude:0,GPSLongitudeRef:''}})).toMatchObject({latitude:null,longitude:null});
 expect(await photoMetadata({...asset,assetId:null,exif:{GPSLatitude:0,GPSLatitudeRef:'N',GPSLongitude:0,GPSLongitudeRef:'E'}})).toMatchObject({latitude:0,longitude:0});
});
test('native compression uploads generated bytes, retries oversize and preserves dimensions',async()=>{
 manipulate.mockResolvedValue({uri:'file:///compressed.jpg',width:2048,height:1536});
 read.mockResolvedValueOnce(new ArrayBuffer(101)).mockResolvedValueOnce(new ArrayBuffer(90));
 const result=await compressPhoto(asset,2048,100);
 expect(result.bytes.byteLength).toBe(90);expect(result.width).toBe(2048);
 expect(manipulate).toHaveBeenNthCalledWith(1,asset.uri,[{resize:{width:2048}}],{compress:.8,format:'jpeg'});
 expect(manipulate).toHaveBeenCalledTimes(2);
});
test('compression failure prevents upload, and small images are not enlarged',async()=>{
 manipulate.mockResolvedValue({uri:'file:///compressed.jpg',width:2,height:2});read.mockResolvedValue(new ArrayBuffer(101));
 await expect(compressPhoto({...asset,width:2,height:2},512,100)).rejects.toThrow('사진 압축');
 expect(manipulate.mock.calls.every(call=>call[1].length===0)).toBe(true);
});
test('limited access is explained and denied EXIF access retains picker metadata',async()=>{
 permission.mockResolvedValue({granted:true,accessPrivileges:'limited'});expect(await photoPermission()).toBe(false);
 expect(permission).toHaveBeenCalledWith(false,['photo']);
 info.mockRejectedValue(new Error('Permission denied'));
 expect(await photoMetadata({...asset,exif:{DateTimeOriginal:'2026:11:01 12:00:00'}})).toMatchObject({captured_date:'2026-11-01',latitude:null});
 info.mockResolvedValue({exif:{DateTimeOriginal:'2026:11:01 12:00:00'},location:{latitude:-33,longitude:126}});
 expect(await photoMetadata(asset)).toMatchObject({captured_date:'2026-11-01',latitude:-33,longitude:126});
});

test('TC-PHOTO-GPS-001: invalid EXIF and library GPS are missing while valid metadata stays intact',async()=>{
 const exif={DateTimeOriginal:'2026:01:10 00:15:00',OffsetTimeOriginal:'+09:00',GPSLatitude:-33,GPSLatitudeRef:'S',GPSLongitude:-126,GPSLongitudeRef:'W'};
 for(const [latitude,longitude] of [[91,181],[NaN,Infinity],[-Infinity,-181]]){
  expect(await photoMetadata({...asset,assetId:null,exif:{...exif,GPSLatitude:latitude,GPSLongitude:longitude}})).toMatchObject({captured_date:'2026-01-10',captured_at:'2026-01-09T15:15:00.000Z',latitude:null,longitude:null});
  info.mockResolvedValue({location:{latitude,longitude}});
  expect(await photoMetadata({...asset,exif})).toMatchObject({latitude:-33,longitude:-126});
 }
 info.mockResolvedValue({location:{latitude:0,longitude:0}});expect(await photoMetadata({...asset,exif})).toMatchObject({latitude:0,longitude:0});
 info.mockResolvedValue({location:{latitude:37.56,longitude:126.98}});expect(await photoMetadata({...asset,exif:{GPSLatitude:91,GPSLongitude:181}})).toMatchObject({latitude:37.56,longitude:126.98});
});
